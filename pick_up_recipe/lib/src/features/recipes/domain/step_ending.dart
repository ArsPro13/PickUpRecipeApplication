// Один вопрос к шагу: заканчивает его человек или таймер?
//
// Ответ нужен двум экранам сразу, и поводы у них разные. Экран заваривания
// решает, что поставить вместо обратного отсчёта: кнопку «сделал» или
// секунды. Конструктор рецепта — показывать ли поле времени у шага, у
// которого времени быть не может. Поводы разные, вопрос один.
//
// И отвечать на него в двух местах порознь нельзя. Стоит условиям чуть
// разойтись — и шаг, заведённый в конструкторе как «по кнопке», в плеере
// промотается сам по нулевому таймеру. Расхождение при этом не поймает ни
// один тест экрана: каждый экран по отдельности останется прав. Заметит его
// человек с чашкой в руках, посреди пролива.
//
// Здесь же соседние вопросы — «показывает длительность» и «показывает воду»:
// это ответы про тот же шаг, и разносить их по разным местам значило бы
// снова спрашивать дважды.
//
// Расширениями, а не полями класса: RecipeStep собирает json_serializable, и
// геттер, добавленный в сам класс, уехал бы в toJson, то есть в запрос к
// серверу. Расширение генератор не видит вовсе.

import 'brew_step.dart';
import 'models/recipe_step_model.dart';
import 'models/user_step_type_model.dart';

/// Способ завершения из справочника своих типов.
extension StepEndsWithFacts on StepEndsWith {
  /// Шаг заканчивает человек, а не таймер.
  ///
  /// «По признаку» — тоже человек: что воронка опустела, видит он, а
  /// приложение об этом не узнаёт никак. Таймер там в лучшем случае ориентир.
  bool get endsByHuman => this != StepEndsWith.timer;

  /// Длительность у такого шага имеет смысл.
  bool get showsDuration => !endsByHuman;
}

/// Заготовка своего типа шага.
extension UserStepTypeFacts on UserStepType {
  /// Шаг заканчивает человек, а не таймер.
  bool get endsByHuman => endsWith.endsByHuman;

  /// Длительность у такого шага имеет смысл.
  bool get showsDuration => endsWith.showsDuration;

  /// Шаг считает воду. У заготовок это отдельный признак: «свой шаг воду не
  /// считает — для воды есть пролив», и человек включает её осознанно.
  bool get showsWater => hasWater;
}

/// Шаг рецепта в конструкторе.
extension RecipeStepFacts on RecipeStep {
  /// Шаг заканчивает человек, а не таймер.
  bool get endsByHuman => untilUser || untilSign.isNotEmpty;

  /// Длительность стоит показывать.
  ///
  /// Либо время заканчивает шаг, либо оно уже проставлено ориентиром —
  /// «примерно полторы минуты, пока не осядет пена». Непустое значение не
  /// прячут никогда: из рецепта оно бы не делось, а с глаз исчезло.
  bool get showsDuration => !endsByHuman || time > 0;

  /// Воду стоит показывать: тип шага её принимает или она уже проставлена.
  ///
  /// Про воду решает тип, а не человек: схема разрешает её четырём типам.
  /// Исключение — то же, что у времени: у исторических шагов тип пустой, и
  /// спрятать у них поле значило бы потерять из виду налитые граммы.
  bool get showsWater => BrewStepType.fromWire(stepType).addsWater || water > 0;
}

/// Шаг в том виде, в каком его проигрывает плеер.
extension BrewStepFacts on BrewStep {
  /// Шаг заканчивает человек, а не таймер.
  bool get endsByHuman => untilUser || untilSign.isNotEmpty;

  /// Длительность стоит показывать: она заканчивает шаг или задана ориентиром.
  bool get showsDuration => !endsByHuman || duration > Duration.zero;

  /// Воду стоит показывать: тип шага её принимает или она уже налита.
  bool get showsWater => type.addsWater || waterG > 0;
}
