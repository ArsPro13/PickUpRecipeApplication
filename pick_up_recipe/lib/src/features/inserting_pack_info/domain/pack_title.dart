// Как называется пачка, заведённая руками.
//
// Поля «Название» в форме больше нет: владелец назвал его непонятным, и он
// прав — человек, стоящий над чужой пачкой с телефоном, не знает, что туда
// писать, а обжарщики называют кофе как угодно. Серверу имя при этом нужно:
// pack_name — обязательное поле, и по нему пачка ищется в списке.
//
// Поэтому имя собирается из того, что человек про пачку точно знает:
// страна и регион, а если региона нет — страна и сорт. Получается
// «Бразилия · Серрадо» или «Бразилия · арабика» — то, что и так написано
// второй строкой на карточке, и человек узнаёт свою пачку в списке.

/// Собирает имя пачки из заполненных полей формы.
String packTitleFrom({
  required String country,
  required String region,
  required String variety,
}) {
  final head = country.trim();
  // Регион важнее сорта: он различает две бразильские пачки на полке,
  // а сорт у них, скорее всего, один и тот же.
  final tail = region.trim().isNotEmpty ? region.trim() : variety.trim();

  final parts = [head, tail].where((part) => part.isNotEmpty);
  return parts.join(' · ');
}
