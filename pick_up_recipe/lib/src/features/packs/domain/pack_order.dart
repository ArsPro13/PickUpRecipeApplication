// Порядок пачек на полке.
//
// Владелец: «кофе, добавленный последним, должен быть самым ранним, то есть
// сортировка должна быть по дате добавления». На видео он заводит пачку и
// находит её второй строкой, под той, что лежит там с прошлой недели: сервер
// отдаёт полку в порядке появления, и новое оказывается внизу.
//
// Сортировка здесь, а не параметром запроса: полка показывается и без сети,
// из кеша, и порядок обязан быть одним и тем же в обоих случаях.

import 'models/pack_model.dart';

/// Полка сверху вниз: последняя заведённая пачка первой.
///
/// По `pack_id`, а не по дате обжарки: дату обжарки человек печатает сам, и
/// у половины пачек её нет вовсе, а «когда завели» отдельным полем не
/// приезжает. Идентификатор выдаёт база по порядку, и для «кто позже» он
/// точнее любой печатной даты.
List<PackData> newestFirst(List<PackData> packs) {
  return [...packs]..sort((a, b) => b.packId.compareTo(a.packId));
}
