// Цвет семьи прибора.
//
// Акцент в приложении один — кофейно-коричневый, и им покрашено всё. При
// семидесяти двух приборах это делает каталог однородной массой: воронка,
// френч-пресс и колд брю выглядят одинаково, хотя ведут себя по-разному.
//
// Семья прибора уже приходит из справочника (brew_method_groups), поэтому
// цвет не выдумывается, а берётся из данных. Четыре приглушённых оттенка
// одной температуры — не радуга: они живут в мелочах (метка прибора, кружок
// значка, полоса на карточке), а кнопки остаются коричневыми. Иначе
// интерфейс распадается на четыре разных приложения.

import 'package:flutter/material.dart';

/// Цвет по slug семьи. Незнакомая семья и метод без семьи получают null —
/// такой элемент красится акцентом, как и раньше.
Color? methodFamilyColor(String? groupSlug) {
  return switch (groupSlug) {
    'pourover' || 'pour_over' || 'drip' => const Color(0xFF8E6341), // охра
    'immersion' || 'full_immersion' => const Color(0xFF5C7A6B), // зелень
    'pressure' || 'espresso' => const Color(0xFF8C5B6B), // вино
    'cold' || 'cold_brew' => const Color(0xFF5A7290), // сине-серый
    _ => null,
  };
}
